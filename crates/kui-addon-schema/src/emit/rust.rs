//! Rust: a crate (`rust/Cargo.toml`, `rust/src/lib.rs`) of props structs
//! with builders and `place` functions:
//! `kit::Button::new("Run").variant(kit::Variant::Primary).on_press(Msg::Run).place(ui)`.

use std::fmt::Write;

use crate::{Component, File, Schema, Type, pascal, wrap};

/// A Rust keyword a field name may not be.
fn ident(name: &str) -> String {
    match name {
        "type" | "match" | "loop" | "move" | "ref" | "self" | "use" | "where" | "mod" | "fn"
        | "impl" | "trait" | "struct" | "enum" | "const" | "static" | "box" | "in" | "as" => {
            format!("r#{name}")
        }
        n => n.to_string(),
    }
}

/// The field's Rust type, as the struct holds it.
fn ty(t: &Type) -> String {
    match t {
        Type::String => "String".into(),
        Type::Number => "f64".into(),
        Type::Integer => "i64".into(),
        Type::Boolean => "bool".into(),
        Type::Color => "Paint".into(),
        Type::Length => "Length".into(),
        Type::Channel => "Channel".into(),
        Type::Any => "Value".into(),
        Type::Named(n) => n.clone(),
        Type::List(t) => format!("Vec<{}>", ty(t)),
        Type::Optional(t) => format!("Option<{}>", ty(t)),
    }
}

/// What a setter takes for a field of this type.
fn arg(t: &Type) -> String {
    match t {
        Type::String => "impl Into<String>".into(),
        Type::Color => "impl Into<Paint>".into(),
        Type::Length => "impl Into<Length>".into(),
        Type::Any => "impl Into<Value>".into(),
        Type::Optional(t) => arg(t),
        t => ty(t),
    }
}

/// How a setter stores what it took.
fn store(t: &Type, v: &str) -> String {
    match t {
        Type::String | Type::Color | Type::Length | Type::Any => format!("{v}.into()"),
        Type::Optional(inner) => format!("Some({})", store(inner, v)),
        _ => v.to_string(),
    }
}

/// An expression turning `v` (a reference to the field) into a `Value`.
fn to_value(t: &Type, v: &str) -> String {
    match t {
        Type::String => format!("Value::str({v}.as_str())"),
        Type::Number => format!("Value::Float(*{v})"),
        Type::Integer => format!("Value::Int(*{v})"),
        Type::Boolean => format!("Value::Bool(*{v})"),
        Type::Color | Type::Length | Type::Named(_) => format!("{v}.to_value()"),
        Type::Channel => format!("{v}.handle()"),
        Type::Any => format!("{v}.clone()"),
        Type::List(inner) => format!(
            "Value::List({v}.iter().map(|x| {}).collect())",
            to_value(inner, "x")
        ),
        Type::Optional(_) => unreachable!("optional handled by the caller"),
    }
}

fn rust_doc(doc: &str, indent: &str) -> String {
    wrap(doc, &format!("{indent}/// "), 80)
}

pub fn files(schema: &Schema) -> Vec<File> {
    vec![
        File {
            path: "rust/Cargo.toml".into(),
            text: cargo(schema),
        },
        File {
            path: "rust/src/lib.rs".into(),
            text: lib(schema),
        },
    ]
}

fn cargo(schema: &Schema) -> String {
    let a = &schema.addon;
    format!(
        "# Generated by kui-addon-schema from {a}'s schema.lua (ADR 0066); do not edit.\n\
         [package]\nname = \"kui-{a}\"\nversion.workspace = true\nedition.workspace = true\n\
         license.workspace = true\nrepository.workspace = true\n\
         description = \"Typed wrappers for {a}'s components (generated, ADR 0066)\"\npublish = false\n\n\
         [dependencies]\nkui-core.workspace = true\n"
    )
}

fn has_children(c: &Component) -> bool {
    !c.children.is_empty()
}

fn lib(schema: &Schema) -> String {
    let a = &schema.addon;
    let mut s = super::banner("//", schema);
    s.push_str(&wrap(&schema.doc, "//! ", 80));
    let _ = writeln!(
        s,
        "//!\n//! Each component is a props struct: `new` takes the props it needs, a\n\
         //! setter each the rest, and `place` puts it in a view under the namespace\n\
         //! `{a}` (`place_in` under another, for {a} loaded twice).\n\n\
         #![allow(clippy::new_without_default, clippy::too_many_arguments)]\n\n\
         use kui_core::channel::Channel;\nuse kui_core::{{FillAnswer, Ui, Value}};\n\n\
         /// The namespace the components are placed under unless told otherwise.\n\
         pub const NAMESPACE: &str = \"{a}\";\n"
    );
    s.push_str(
        "/// A colour prop: `0xRRGGBBAA`, or a `$token`.\n\
         #[derive(Clone, Debug, PartialEq)]\npub enum Paint {\n    Hex(u32),\n    Token(String),\n}\n\n\
         impl Paint {\n    pub fn to_value(&self) -> Value {\n        match self {\n            \
         Paint::Hex(c) => Value::Int(i64::from(*c)),\n            Paint::Token(t) => Value::str(t.as_str()),\n        }\n    }\n}\n\n\
         impl From<u32> for Paint {\n    fn from(c: u32) -> Self {\n        Paint::Hex(c)\n    }\n}\n\n\
         impl From<kui_core::Color> for Paint {\n    fn from(c: kui_core::Color) -> Self {\n        Paint::Hex(c.to_hex())\n    }\n}\n\n\
         impl From<&str> for Paint {\n    fn from(t: &str) -> Self {\n        Paint::Token(t.to_string())\n    }\n}\n\n\
         /// A length prop: logical px, or a `$token`.\n\
         #[derive(Clone, Debug, PartialEq)]\npub enum Length {\n    Px(f64),\n    Token(String),\n}\n\n\
         impl Length {\n    pub fn to_value(&self) -> Value {\n        match self {\n            \
         Length::Px(px) => Value::Float(*px),\n            Length::Token(t) => Value::str(t.as_str()),\n        }\n    }\n}\n\n\
         impl From<f64> for Length {\n    fn from(px: f64) -> Self {\n        Length::Px(px)\n    }\n}\n\n\
         impl From<f32> for Length {\n    fn from(px: f32) -> Self {\n        Length::Px(f64::from(px))\n    }\n}\n\n\
         impl From<&str> for Length {\n    fn from(t: &str) -> Self {\n        Length::Token(t.to_string())\n    }\n}\n\n",
    );
    for e in &schema.enums {
        s.push_str(&rust_doc(&e.doc, ""));
        let _ = writeln!(
            s,
            "#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]\npub enum {} {{",
            e.name
        );
        for (i, v) in e.values.iter().enumerate() {
            if i == 0 {
                s.push_str("    #[default]\n");
            }
            let _ = writeln!(s, "    {},", pascal(v));
        }
        let _ = writeln!(
            s,
            "}}\n\nimpl {} {{\n    /// The value's name on the wire.\n    pub fn as_str(self) -> &'static str {{\n        match self {{",
            e.name
        );
        for v in &e.values {
            let _ = writeln!(s, "            {}::{} => \"{v}\",", e.name, pascal(v));
        }
        s.push_str("        }\n    }\n\n    pub fn to_value(&self) -> Value {\n        Value::str(self.as_str())\n    }\n}\n\n");
    }
    for r in &schema.records {
        s.push_str(&rust_doc(&r.doc, ""));
        let _ = writeln!(
            s,
            "#[derive(Clone, Debug, PartialEq)]\npub struct {} {{",
            r.name
        );
        for f in &r.fields {
            s.push_str(&rust_doc(&f.doc, "    "));
            let _ = writeln!(s, "    pub {}: {},", ident(&f.name), ty(&f.ty));
        }
        let _ = writeln!(s, "}}\n\nimpl {} {{", r.name);
        new_head(&mut s, &r.fields);
        for f in &r.fields {
            new_field(&mut s, f);
        }
        s.push_str("        }\n    }\n\n");
        setters(&mut s, &r.fields);
        s.push_str("    /// As the extension reads it.\n    pub fn to_value(&self) -> Value {\n        let mut m: Vec<(String, Value)> = Vec::new();\n");
        for f in &r.fields {
            push_field(&mut s, &f.name, &f.ty, "self");
        }
        s.push_str("        Value::Map(m)\n    }\n}\n\n");
    }
    for c in &schema.components {
        component(&mut s, schema, c);
    }
    s
}

/// `pub fn new(<the required fields>) -> Self { Self {`, left open for the
/// fields.
fn new_head(s: &mut String, fields: &[crate::Field]) {
    let args: Vec<String> = fields
        .iter()
        .filter(|f| f.ty.required().1)
        .map(|f| format!("{}: {}", ident(&f.name), arg(&f.ty)))
        .collect();
    let _ = writeln!(
        s,
        "    /// What it needs; the rest by their setters.\n    pub fn new({}) -> Self {{\n        Self {{",
        args.join(", ")
    );
}

/// One field of `new`'s `Self { … }`: the argument, or `None`.
fn new_field(s: &mut String, f: &crate::Field) {
    let v = if f.ty.required().1 {
        store(&f.ty, &ident(&f.name))
    } else {
        "None".to_string()
    };
    let _ = writeln!(s, "            {}: {v},", ident(&f.name));
}

/// A builder setter for each optional field.
fn setters(s: &mut String, fields: &[crate::Field]) {
    for f in fields.iter().filter(|f| !f.ty.required().1) {
        s.push_str(&rust_doc(&f.doc, "    "));
        let _ = writeln!(
            s,
            "    pub fn {}(mut self, v: {}) -> Self {{\n        self.{} = {};\n        self\n    }}\n",
            ident(&f.name),
            arg(&f.ty),
            ident(&f.name),
            store(&f.ty, "v")
        );
    }
}

/// Pushes a field onto `m` from `owner.<name>`, skipping an unset optional.
fn push_field(s: &mut String, name: &str, t: &Type, owner: &str) {
    let field = format!("{owner}.{}", ident(name));
    match t {
        Type::Optional(inner) => {
            let _ = writeln!(
                s,
                "        if let Some(v) = &{field} {{\n            m.push((\"{name}\".into(), {}));\n        }}",
                to_value(inner, "v")
            );
        }
        _ => {
            let _ = writeln!(
                s,
                "        m.push((\"{name}\".into(), {}));",
                to_value(t, &format!("(&{field})"))
            );
        }
    }
}

fn component(s: &mut String, schema: &Schema, c: &Component) {
    let a = &schema.addon;
    let p = pascal(&c.name);
    s.push_str(&rust_doc(&c.doc, ""));
    let _ = writeln!(s, "#[derive(Clone, Debug, PartialEq)]\npub struct {p} {{");
    for f in &c.props {
        s.push_str(&rust_doc(&f.doc, "    "));
        let _ = writeln!(s, "    pub {}: {},", ident(&f.name), ty(&f.ty));
    }
    for e in &c.events {
        s.push_str(&rust_doc(
            &format!(
                "The message `{}` arrives as, with `{}: {p}{}` in it. {}",
                e.name,
                e.name,
                pascal(&e.name),
                e.doc
            ),
            "    ",
        ));
        let _ = writeln!(s, "    pub on_{}: Option<Value>,", e.name);
    }
    s.push_str(
        "    /// Keys the instance; by default it is keyed by where it is placed.\n    pub key: Option<String>,\n    \
         /// Asks the extension every frame instead of replaying an unchanged instance.\n    pub fresh: bool,\n}\n\n",
    );
    let _ = writeln!(s, "impl {p} {{");
    new_head(s, &c.props);
    for f in &c.props {
        new_field(s, f);
    }
    for e in &c.events {
        let _ = writeln!(s, "            on_{}: None,", e.name);
    }
    s.push_str("            key: None,\n            fresh: false,\n        }\n    }\n\n");
    setters(s, &c.props);
    for e in &c.events {
        s.push_str(&rust_doc(
            &format!("The message `{}` arrives as. {}", e.name, e.doc),
            "    ",
        ));
        let _ = writeln!(
            s,
            "    pub fn on_{}(mut self, msg: impl Into<Value>) -> Self {{\n        self.on_{} = Some(msg.into());\n        self\n    }}\n",
            e.name, e.name
        );
    }
    s.push_str(
        "    /// Keys the instance.\n    pub fn key(mut self, key: impl Into<String>) -> Self {\n        self.key = Some(key.into());\n        self\n    }\n\n\
         /// Asks the extension every frame.\n    pub fn fresh(mut self) -> Self {\n        self.fresh = true;\n        self\n    }\n\n\
         /// The props as the extension reads them.\n    pub fn props(&self) -> Value {\n        let mut m: Vec<(String, Value)> = Vec::new();\n",
    );
    for f in &c.props {
        push_field(s, &f.name, &f.ty, "self");
    }
    for e in &c.events {
        let _ = writeln!(
            s,
            "        if let Some(v) = &self.on_{} {{\n            m.push((\"on_{}\".into(), v.clone()));\n        }}",
            e.name, e.name
        );
    }
    s.push_str(
        "        if let Some(k) = &self.key {\n            m.push((\"key\".into(), Value::str(k.as_str())));\n        }\n        \
         if self.fresh {\n            m.push((\"fresh\".into(), Value::Bool(true)));\n        }\n        Value::Map(m)\n    }\n\n",
    );
    let _ = writeln!(
        s,
        "    /// Places it under `{a}/{}`.\n    pub fn place(&self, ui: &mut Ui<'_>) -> Option<FillAnswer> {{\n        ui.component(\"{a}/{}\", &self.props())\n    }}\n\n    \
         /// Places it under `<namespace>/{}`.\n    pub fn place_in(&self, ui: &mut Ui<'_>, namespace: &str) -> Option<FillAnswer> {{\n        ui.component(&format!(\"{{namespace}}/{}\"), &self.props())\n    }}",
        c.name, c.name, c.name, c.name
    );
    if has_children(c) {
        let groups: Vec<String> = c
            .children
            .iter()
            .map(|g| {
                if g.name.is_empty() {
                    "`\"\"` (the unnamed group)".to_string()
                } else {
                    format!("`\"{}\"`", g.name)
                }
            })
            .collect();
        let _ = writeln!(
            s,
            "\n    /// Places it with your children: `children(group, ui)` builds {} where it asks.\n    \
             pub fn place_with(&self, ui: &mut Ui<'_>, children: impl FnMut(&str, &mut Ui<'_>)) -> Option<FillAnswer> {{\n        \
             ui.component_with(\"{a}/{}\", &self.props(), children)\n    }}",
            groups.join(", "),
            c.name
        );
    }
    s.push_str("}\n\n");
    for e in &c.events {
        let _ = writeln!(
            s,
            "/// What `on_{}`'s message carries under `{}`.\n#[derive(Clone, Debug, Default, PartialEq)]\npub struct {p}{} {{",
            e.name,
            e.name,
            pascal(&e.name)
        );
        for f in &e.fields {
            s.push_str(&rust_doc(&f.doc, "    "));
            let _ = writeln!(s, "    pub {}: {},", ident(&f.name), ty(&f.ty));
        }
        let _ = writeln!(
            s,
            "}}\n\nimpl {p}{} {{\n    /// Read off an event's payload: the fields under `{}`.\n    pub fn from_payload(payload: &Value) -> Option<Self> {{\n        let _d = payload.get(\"{}\")?;\n        Some(Self {{",
            pascal(&e.name),
            e.name,
            e.name
        );
        for f in &e.fields {
            let read = match f.ty.required().0 {
                Type::String => format!("_d.get_str(\"{}\").map(str::to_string)", f.name),
                Type::Number => format!("_d.get(\"{}\").and_then(Value::as_float)", f.name),
                Type::Integer => format!("_d.get(\"{}\").and_then(Value::as_int)", f.name),
                Type::Boolean => format!("_d.get(\"{}\").and_then(Value::as_bool)", f.name),
                Type::Any => format!("_d.get(\"{}\").cloned()", f.name),
                _ => "None".to_string(),
            };
            if f.ty.required().1 {
                let _ = writeln!(
                    s,
                    "            {}: {read}.unwrap_or_default(),",
                    ident(&f.name)
                );
            } else {
                let _ = writeln!(s, "            {}: {read},", ident(&f.name));
            }
        }
        s.push_str("        })\n    }\n}\n\n");
    }
}
