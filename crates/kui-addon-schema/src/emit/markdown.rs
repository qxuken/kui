//! Markdown: the add-on's component reference (`reference.md`, ADR 0071,
//! decision 9) — every component with its props, events and child groups,
//! then the enums and records they name. One section a component, headed
//! `## <addon>.<name>`, so a reader (or `kui docs <query>`, which reads it)
//! finds one by its name. Lua's snake_case spelling first, Node's beside it.

use std::fmt::Write;

use crate::{Component, File, Schema, Type, camel, pascal};

pub fn files(schema: &Schema) -> Vec<File> {
    vec![File {
        path: "reference.md".into(),
        text: reference(schema),
    }]
}

/// A table cell: one line, its pipes escaped.
fn cell(s: &str) -> String {
    s.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('|', "\\|")
}

/// The anchor GitHub and mdBook give a `### Name` heading.
fn anchor(name: &str) -> String {
    name.to_lowercase()
}

/// A type as the schema spells it, its enums and records linked to their
/// sections.
fn ty(t: &Type) -> String {
    match t {
        Type::String => "string".into(),
        Type::Number => "number".into(),
        Type::Integer => "integer".into(),
        Type::Boolean => "boolean".into(),
        Type::Color => "color".into(),
        Type::Length => "length".into(),
        Type::Channel => "channel".into(),
        Type::Any => "any".into(),
        Type::Named(n) => format!("[{n}](#{})", anchor(n)),
        Type::List(t) => format!("{{{}}}", ty(t)),
        Type::Optional(t) => format!("{}?", ty(t)),
    }
}

fn reference(schema: &Schema) -> String {
    let a = &schema.addon;
    let mut s = String::new();
    let _ = writeln!(s, "# {} component reference\n", pascal(a));
    let _ = writeln!(
        s,
        "*Generated by kui-addon-schema from {a}'s schema.lua (ADR 0066); do not edit.*\n"
    );
    let _ = writeln!(s, "{}\n", schema.doc);
    let _ = writeln!(
        s,
        "Lua places a component with `{a}.<name>(props, children)` after \
         `local {a} = require(\"{a}.ui\")`; Node with `<Name … />` or `Name({{ … }})` from \
         `@qxuken/kui/{a}`. Props are snake_case in Lua and camelCase in Node. An event \
         `<event>` is the prop `on_<event>` (`on<Event>`): the message it arrives as in \
         `update`, the event's fields under `<event>`. A prop's type ending in `?` may be \
         left out; `{{T}}` is a list of `T`; a colour is `0xRRGGBBAA` or a `$token`, a \
         length px or a `$token`. Every component also takes `key` and `fresh`.\n"
    );
    let _ = writeln!(s, "## Contents\n");
    let names: Vec<String> = schema
        .components
        .iter()
        .map(|c| format!("[`{a}.{}`](#{a}{})", c.name, c.name))
        .collect();
    let _ = writeln!(s, "Components: {}.\n", names.join(", "));
    let types: Vec<String> = schema
        .enums
        .iter()
        .map(|e| &e.name)
        .chain(schema.records.iter().map(|r| &r.name))
        .map(|n| format!("[`{n}`](#{})", anchor(n)))
        .collect();
    let _ = writeln!(s, "Types: {}.\n", types.join(", "));
    for c in &schema.components {
        component(&mut s, a, c);
    }
    let _ = writeln!(s, "## Types\n");
    let _ = writeln!(s, "The enums and records the props name.\n");
    for e in &schema.enums {
        let _ = writeln!(s, "### {}\n\n{}\n", e.name, e.doc);
        let values: Vec<String> = e.values.iter().map(|v| format!("`\"{v}\"`")).collect();
        let _ = writeln!(s, "One of {}.\n", values.join(", "));
    }
    for r in &schema.records {
        let _ = writeln!(s, "### {}\n\n{}\n", r.name, r.doc);
        let _ = writeln!(
            s,
            "| field | Node | type | description |\n|---|---|---|---|"
        );
        for f in &r.fields {
            let _ = writeln!(
                s,
                "| `{}` | `{}` | {} | {} |",
                f.name,
                camel(&f.name),
                ty(&f.ty),
                cell(&f.doc)
            );
        }
        s.push('\n');
    }
    s.truncate(s.trim_end().len());
    s.push('\n');
    s
}

fn component(s: &mut String, a: &str, c: &Component) {
    let _ = writeln!(s, "## {a}.{}\n", c.name);
    let _ = writeln!(s, "{}\n", c.doc);
    let call = if c.children.is_empty() {
        "props"
    } else {
        "props, children"
    };
    let _ = writeln!(
        s,
        "Lua `{a}.{}({call})` · Node `<{} />`\n",
        c.name,
        pascal(&c.name)
    );
    if !c.props.is_empty() {
        let _ = writeln!(s, "| prop | Node | type | description |\n|---|---|---|---|");
        for f in &c.props {
            let _ = writeln!(
                s,
                "| `{}` | `{}` | {} | {} |",
                f.name,
                camel(&f.name),
                ty(&f.ty),
                cell(&f.doc)
            );
        }
        s.push('\n');
    }
    if !c.events.is_empty() {
        let _ = writeln!(
            s,
            "| event | Node | carries | description |\n|---|---|---|---|"
        );
        for e in &c.events {
            let carries = if e.fields.is_empty() {
                "—".to_string()
            } else {
                let fields: Vec<String> = e
                    .fields
                    .iter()
                    .map(|f| format!("`{}`: {} — {}", f.name, ty(&f.ty), cell(&f.doc)))
                    .collect();
                format!("`{}` = {{ {} }}", e.name, fields.join("; "))
            };
            let _ = writeln!(
                s,
                "| `on_{}` | `on{}` | {} | {} |",
                e.name,
                pascal(&e.name),
                carries,
                cell(&e.doc)
            );
        }
        s.push('\n');
    }
    if !c.children.is_empty() {
        let _ = writeln!(s, "Children:\n");
        for g in &c.children {
            if g.name.is_empty() {
                let _ = writeln!(s, "- the list part {}", g.doc);
            } else {
                let _ = writeln!(s, "- `{}` {}", g.name, g.doc);
            }
        }
        s.push('\n');
    }
}
